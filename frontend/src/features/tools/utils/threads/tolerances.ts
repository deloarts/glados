/**
 * Limit dimensions in mm of the medium tolerance class 6H/6g (ISO 965-2) for a
 * selection of common threads, keyed by thread code.
 */
export interface ThreadLimits6H6g {
  /** Internal thread 6H: major diameter min, pitch diameter min/max, minor diameter min/max. */
  internal: { Dmin: number; D2: readonly [min: number, max: number]; D1: readonly [min: number, max: number] }
  /** External thread 6g: major, pitch and minor diameter, each max/min. */
  external: {
    d: readonly [max: number, min: number]
    d2: readonly [max: number, min: number]
    d3: readonly [max: number, min: number]
  }
}

function row(
  Dmin: number,
  D2: [number, number],
  D1: [number, number],
  d: [number, number],
  d2: [number, number],
  d3: [number, number],
): ThreadLimits6H6g {
  return { internal: { Dmin, D2, D1 }, external: { d, d2, d3 } }
}

