/**
 * Inspection checklist for robot systems and their integration, based on
 * ISO 10218-2. The list was drawn up against the 2011 edition; the current
 * edition is structured differently, so items cite the standard without
 * clause numbers. Every item names the verification methods (A to I) by
 * which it is checked.
 */

function r(key: string, methods: string, also: DocumentKey[] = [], options: ItemOptions = {}) {
  return verified(key, methods, [...clauses('iso10218_2'), ...also.flatMap((doc) => clauses(doc))], options)
}

