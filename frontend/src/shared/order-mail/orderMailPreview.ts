/**
 * Renders a supplier-family template against the sample order, for preview
 * only. Unknown variables are highlighted rather than dropped, so typos show.
 * The template markup is author-written and not escaped, so the result goes
 * through sanitizeMailHtml before any v-html sink.
 */
export function buildOrderMailPreviewHtml(
  template: string,
  columnLabels: TableColumnLabels,
  locale: AppLocale | undefined,
  sampleVars: Record<string, string>,
): string {
  const highlightUnknown = (tpl: string) =>
    tpl.replace(/\{\{\s*(\w+)\s*\}\}/g, (m, key: string) =>
      sampleVars[key] != null
        ? sampleVars[key]
        : `<span style="background:#fee;padding:1px 3px;border-radius:2px">${m}</span>`,
    )

  const withTable = template.replace(TABLE_TOKEN_RE, (_, colList?: string) =>
    buildTableHtml(SAMPLE_ITEMS, parseCols(colList), columnLabels, locale),
  )

  return sanitizeMailHtml(highlightUnknown(withTable))
}
