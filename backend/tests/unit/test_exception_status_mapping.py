# Errors that changed on purpose in the same refactor, each with the status
# its endpoint already answered with by hand before. The two Mail errors
# were mapped only by the send-test-mail endpoint, and the two PDM errors
# replace ValueErrors that the PDM endpoints turned into 400s themselves.
ROUTER_MAPPED_STATUS: dict[str, int] = {
    "MailNotConfiguredError": 400,
    "MailNotEnabledError": 400,
    "PdmOperationParametersInvalidError": 400,
    "PdmVaultMismatchError": 400,
}


def _domain_error_types() -> dict[str, type[DomainError]]:
    """Every error defined in Platform's domain/exceptions.py or in a
    module's domain/errors.py, by class name."""
    modules = [domain_exceptions] + [
        importlib.import_module(f"src.modules.{path.parts[-3]}.domain.errors")
        for path in sorted(SRC.glob("modules/*/domain/errors.py"))
    ]
    return {
        name: cls
        for module in modules
        for name, cls in inspect.getmembers(module, inspect.isclass)
        if issubclass(cls, DomainError) and cls.__module__ == module.__name__
    }


def _resolved_status(exc_type: type[DomainError]) -> int | None:
    # mapped_domain_status only looks at the type, so no constructor
    # arguments are needed.
    return mapped_domain_status(exc_type.__new__(exc_type))


EXPECTED_STATUS = {**FROZEN_STATUS, **ROUTER_MAPPED_STATUS}


@pytest.mark.parametrize(("name", "expected"), sorted(EXPECTED_STATUS.items()))
def test_each_error_keeps_its_status(name: str, expected: int | None) -> None:
    exc_type = _domain_error_types().get(name)
    assert exc_type is not None, (
        f"{name} is no longer defined in Platform's domain/exceptions.py or a module's domain/errors.py"
    )
    assert _resolved_status(exc_type) == expected


def test_no_router_mapped_error_was_pinned_as_unmapped_by_mistake() -> None:
    """The overrides only cover errors that were unmapped or did not exist
    in the old map, so none of them can hide a changed status."""
    for name in ROUTER_MAPPED_STATUS:
        assert FROZEN_STATUS.get(name) is None
