def _seeded(value: int) -> Any:
    @seed(value)
    def model() -> LifecycleModel:
        return LifecycleModel()

    return model


def _explore(
    monkeypatch: pytest.MonkeyPatch, seeds: tuple[int, ...] = _SEEDS
) -> set[ObservedTransition]:
    """Runs the exploration on Hypothesis' own constants only, then the
    fixed scenarios. Hypothesis also draws constants it finds in every
    local module that is loaded, so the examples would otherwise depend on
    which other tests the session imported."""
    monkeypatch.setattr(providers, "_get_local_constants", providers.Constants)
    providers.CONSTANTS_CACHE.cache.clear()
    _transitions.RECORDED.clear()
    try:
        for value in seeds:
            run_state_machine_as_test(_seeded(value), settings=_EXPLORATION)
    finally:
        providers.CONSTANTS_CACHE.cache.clear()
    for scenario in SCENARIOS:
        scenario()
    return set(_transitions.RECORDED)


def _order(t: ObservedTransition) -> tuple[str, ...]:
    return (t.machine, t.from_state or "", t.to_state, t.trigger, t.subject)


def _literal(value: str | None) -> str:
    return "None" if value is None else json.dumps(value)


def _render(transitions: set[ObservedTransition]) -> str:
    """The table module, in the layout ruff formats it to."""
    rows = "".join(
        "    ObservedTransition(\n"
        + "".join(
            f"        {_literal(part)},\n"
            for part in (t.machine, t.from_state, t.to_state, t.trigger, t.subject)
        )
        + "    ),\n"
        for t in sorted(transitions, key=_order)
    )
    return f"{_HEADER}TRANSITIONS: tuple[ObservedTransition, ...] = (\n{rows})\n"


def test_the_transition_table_lists_what_the_code_does(monkeypatch: pytest.MonkeyPatch) -> None:
    if os.environ.get("GLADOS_WRITE_TRANSITIONS") == "1":
        _TABLE.write_text(_render(_explore(monkeypatch, _DEEP_SEEDS)))
        return

    found = _explore(monkeypatch)
    unlisted = sorted(found - set(observed_transitions.TRANSITIONS))
    hint = "run this test with GLADOS_WRITE_TRANSITIONS=1 and review the diff"
    assert not unlisted, f"transitions the table does not list ({hint}): {unlisted}"
