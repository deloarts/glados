"""
The handbook's state transition tables are computed, never written by hand:
the lifecycle model explores the real use cases on fixed seeds, and every
status change it sees is one row. Transitions the exploration reaches only
now and then are driven on purpose by the fixed scenarios of
test_rare_transitions.py, which record theirs the same way. The generated
table (src/modules/fulfillment/domain/services/lifecycle/observed_transitions.py) must list
everything the exploration and the scenarios find, so a transition the code
makes that the table does not list fails here. With GLADOS_WRITE_TRANSITIONS=1 the test writes the
table instead, from a deeper exploration over more seeds, so rare
transitions stay in the handbook even when a change shifts which examples
the shorter exploration draws; a transition the code no longer makes drops
out at that regeneration, which shows it in the diff.
"""

