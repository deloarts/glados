# A fixed exploration: the same examples on every run, without the example
# database, so the table changes only when the code or the model does. The seed is
# explicit because derandomize seeds from a digest of the model's source,
# so any edit of the model, even one that changes no behaviour, would draw
# other examples.
_EXPLORATION = settings(
    max_examples=600,
    stateful_step_count=40,
    database=None,
    deadline=None,
    suppress_health_check=list(HealthCheck),
)
_TABLE = Path(observed_transitions.__file__)
_HEADER = '''"""Generated by tests/unit/lifecycle/test_state_transitions.py from the
lifecycle model; do not edit. Run it with GLADOS_WRITE_TRANSITIONS=1 to
regenerate this file after a lifecycle change."""

from src.modules.fulfillment.domain.services.lifecycle.transitions import ObservedTransition

'''


