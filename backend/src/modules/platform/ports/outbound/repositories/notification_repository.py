"""
Abstract interface for notification persistence.
"""

from typing import Protocol
from typing import runtime_checkable

from src.modules.platform.domain.entities.notification import Notification


@runtime_checkable
class INotificationRepository(Protocol):
    async def get_by_user_id(
        self, user_id: int, unread_only: bool = False
    ) -> list[Notification]: ...
    async def get_unread_count(self, user_id: int) -> int: ...
    async def get_by_id(self, notification_id: int) -> Notification | None: ...
    async def exists_by_source_event_id(self, source_event_id: str) -> bool: ...
    async def save(self, notification: Notification) -> Notification: ...
    async def add_for_event(self, notification: Notification) -> bool:
        """Inserts a new notification unless one for the same event and
        user exists, and returns whether it inserted. A concurrent insert of
        the same pair waits for the other transaction and then inserts
        nothing once that one commits."""
        ...

    async def mark_read(self, notification_id: int) -> None: ...
    async def mark_all_read(self, user_id: int) -> None: ...
    async def delete_by_id(self, notification_id: int) -> None: ...
    async def delete_all_by_user_id(self, user_id: int) -> None: ...
