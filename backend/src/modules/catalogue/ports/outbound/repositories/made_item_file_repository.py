"""
Abstract interface for made item file persistence.
"""

from typing import Protocol
from typing import runtime_checkable

from src.modules.catalogue.domain.entities.made_item_file import MadeItemFile
from src.modules.catalogue.domain.value_objects.made_item_file_category import MadeItemFileCategory


@runtime_checkable
class IMadeItemFileRepository(Protocol):
    async def get_by_id(self, id: int) -> MadeItemFile | None: ...
    async def get_by_item_id(self, item_id: int) -> list[MadeItemFile]: ...
    async def get_by_item_ids(self, item_ids: list[int]) -> list[MadeItemFile]: ...
    async def get_by_item_id_and_category(
        self, item_id: int, category: MadeItemFileCategory
    ) -> list[MadeItemFile]: ...
    async def save(self, file: MadeItemFile) -> MadeItemFile: ...
    async def delete(self, file: MadeItemFile) -> None: ...
    async def reassign(self, file_id: int, target_item_id: int) -> None: ...
