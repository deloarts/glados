"""
Writes docs/LIFECYCLES.md, one section per lifecycle with a Mermaid state
diagram, the user actions and, for a derived lifecycle, its decision table.
Everything comes from build_state_machine_catalog, the source the in-app
handbook draws its state machines from, so the page shows what the code
does. The file is generated: tests/unit/test_lifecycle_docs.py fails when it
differs from what this script renders, and it is never edited by hand.

The diagram's arrows are the status changes the code makes (the observed
transitions of lifecycle/observed_transitions.py) and, for a lifecycle set
by user actions alone, its status moves. Several triggers of one arrow share
its label. Status values stay raw, so the page needs no translation.

Usage:
    poetry run python scripts/export_lifecycle_docs.py            # rewrite the page
    poetry run python scripts/export_lifecycle_docs.py --check    # exit 1 on drift
"""

import argparse
import sys
from pathlib import Path

from src.read.domain.services.state_machine_catalog import MachineGraph
from src.read.domain.services.state_machine_catalog import MachineKind
from src.read.domain.services.state_machine_catalog import build_state_machine_catalog

DOC_PATH = Path(__file__).resolve().parents[2] / "docs" / "LIFECYCLES.md"

_HEADER = """\
# lifecycles

Generated by `backend/scripts/export_lifecycle_docs.py` from the state
machine catalogue (`src/read/domain/services/state_machine_catalog.py`); never
edit it by hand. After a lifecycle change, run
`poetry run python scripts/export_lifecycle_docs.py` from `backend/`.
The in-app handbook draws the same lifecycles with translated texts.

A **derived** lifecycle computes its status from recorded facts and user
intents with an ordered decision table, the first matching row wins
([CONTRIBUTING.md section 3.7](CONTRIBUTING.md#37-lifecycle-facts-intents-and-the-reconciler)).
An **intent** lifecycle is set by user actions alone. Arrows are the status
changes the code makes, labelled with the requests on the record itself that
make them; `cascade` marks a change that a request on another record, such
as a canceled lot or a moved line, makes too.
"""


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|") or " "


def _state_id(value: str) -> str:
    return f"s_{value}"


def _arrows(graph: MachineGraph) -> dict[tuple[str | None, str], str]:
    """Each arrow with its label: the requests on this lifecycle's own
    aggregate that make it, and `cascade` when a request on another
    aggregate makes it too."""
    own: dict[tuple[str | None, str], set[str]] = {}
    cascades: set[tuple[str | None, str]] = set()
    for edge in graph.edges:
        own.setdefault((edge.from_state, edge.to_state), set())
    for row in graph.transitions:
        arrow = (row.from_state, row.to_state)
        own.setdefault(arrow, set())
        if row.cascade:
            cascades.add(arrow)
        else:
            own[arrow].add(row.trigger)
    return {
        arrow: ", ".join([*sorted(triggers), *(["cascade"] if arrow in cascades else [])])
        for arrow, triggers in own.items()
    }


def _diagram(graph: MachineGraph) -> list[str]:
    lines = ["```mermaid", "stateDiagram-v2"]
    lines += [f'    state "{s.value}" as {_state_id(s.value)}' for s in graph.states]
    lines += [f"    [*] --> {_state_id(s.value)}" for s in graph.states if s.initial]
    for (source, target), label in sorted(
        _arrows(graph).items(), key=lambda item: (item[0][0] or "", item[0][1])
    ):
        start = "[*]" if source is None else _state_id(source)
        lines.append(f"    {start} --> {_state_id(target)}{f': {label}' if label else ''}")
    lines += [f"    {_state_id(s.value)} --> [*]" for s in graph.states if s.terminal]
    lines.append("```")
    return lines


def _section(graph: MachineGraph) -> list[str]:
    kind = "derived" if graph.kind is MachineKind.DERIVED else "intent"
    lines = [f"## {graph.entity} (`{graph.key}`)", ""]
    if graph.description:
        lines += [" ".join(graph.description.split()), ""]
    lines += [f"Kind: {kind}. States: {', '.join(f'`{s.value}`' for s in graph.states)}.", ""]
    lines += _diagram(graph)
    if graph.intents:
        lines += [
            "",
            "| Action | Starts from | Sets | Condition | Permission |",
            "| ------ | ----------- | ---- | --------- | ---------- |",
        ]
        for row in graph.intents:
            starts = "any" if row.allowed_from is None else ", ".join(row.allowed_from)
            lines.append(
                f"| `{row.action}` | {_cell(starts)} | {_cell(row.target or '')} "
                f"| {_cell(row.condition)} | {_cell(row.permission)} |"
            )
    if graph.rules:
        lines += [
            "",
            "| Row | Condition | Status |",
            "| --- | --------- | ------ |",
        ]
        lines += [
            f"| {row.number} | {_cell(row.condition)} | {_cell(row.result)} |"
            for row in graph.rules
        ]
    return lines


def render() -> str:
    """The page for the current lifecycles."""
    graphs = build_state_machine_catalog()
    # Each header paragraph goes out as one line, so the page reads well on narrow screens.
    header = "\n\n".join(" ".join(p.split()) for p in _HEADER.strip().split("\n\n"))
    lines = [header, "", "| Lifecycle | Kind | States |", "| --- | --- | --- |"]
    for graph in graphs:
        kind = "derived" if graph.kind is MachineKind.DERIVED else "intent"
        lines.append(f"| {graph.entity} (`{graph.key}`) | {kind} | {len(graph.states)} |")
    for graph in graphs:
        lines += ["", *_section(graph)]
    return "\n".join(lines) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument("--check", action="store_true", help="exit 1 when the page is stale")
    args = parser.parse_args()
    page = render()
    if args.check:
        if not DOC_PATH.exists() or DOC_PATH.read_text(encoding="utf-8") != page:
            print(f"{DOC_PATH} is stale; run scripts/export_lifecycle_docs.py", file=sys.stderr)
            return 1
        return 0
    DOC_PATH.write_text(page, encoding="utf-8")
    print(f"wrote {DOC_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
