"""
Lists functions in src/ whose body spans more than 100 lines, so oversized
functions stay visible in CI. Ruff has no line-based function length rule
(PLR0915 counts statements) and cannot report a rule as a warning, which is
why this is a small standalone check.

A function's length is the span from its `def` line to its last line,
docstring and comments included, decorators excluded. Files that are
generated or intentionally long are listed in EXEMPT_FILES.

By default the script only reports and exits 0. With --strict it exits 1
when any function is over the limit.

Usage:
    poetry run python scripts/check_function_length.py [--strict] [--max-lines N]
"""

import argparse
import ast
import sys
from pathlib import Path

BACKEND_ROOT = Path(__file__).resolve().parent.parent
SOURCE_ROOT = BACKEND_ROOT / "src"
DEFAULT_MAX_LINES = 100

# Paths relative to backend/. The PDM catalogue is generated by
# scripts/pdm_catalogue/ and mirrors the vendor's Web API reference.
EXEMPT_FILES = frozenset(
    {
        "src/modules/external_data/adapters/outbound/external/pdm/catalogue.py",
    }
)


def find_long_functions(path: Path, max_lines: int) -> list[tuple[int, str, int]]:
    """Return (line, qualified name, length) for every function in the file over the limit."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    found: list[tuple[int, str, int]] = []

    def visit(node: ast.AST, prefix: str) -> None:
        for child in ast.iter_child_nodes(node):
            if isinstance(child, ast.FunctionDef | ast.AsyncFunctionDef):
                name = f"{prefix}{child.name}"
                length = (child.end_lineno or child.lineno) - child.lineno + 1
                if length > max_lines:
                    found.append((child.lineno, name, length))
                visit(child, f"{name}.")
            elif isinstance(child, ast.ClassDef):
                visit(child, f"{prefix}{child.name}.")
            else:
                visit(child, prefix)

    visit(tree, "")
    return found


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[1])
    parser.add_argument("--strict", action="store_true", help="exit 1 when a function is too long")
    parser.add_argument("--max-lines", type=int, default=DEFAULT_MAX_LINES)
    args = parser.parse_args()

    violations: list[str] = []
    for path in sorted(SOURCE_ROOT.rglob("*.py")):
        relative = path.relative_to(BACKEND_ROOT).as_posix()
        if relative in EXEMPT_FILES:
            continue
        for line, name, length in find_long_functions(path, args.max_lines):
            violations.append(f"{relative}:{line}: {name} has {length} lines")

    for violation in violations:
        print(violation)
    print(f"{len(violations)} function(s) over {args.max_lines} lines.")
    return 1 if args.strict and violations else 0


if __name__ == "__main__":
    sys.exit(main())
